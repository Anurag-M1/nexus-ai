/**
 * Call the Google Gemini API with a prompt and optional system instruction.
 * @param {string} apiKey - Gemini API key
 * @param {string} model - Model name (e.g., 'gemini-2.0-flash')
 * @param {string} prompt - User prompt
 * @param {string} systemInstruction - Optional system instruction
 * @returns {Promise<string>} - Generated text response
 */
export async function callGemini(apiKey, model, prompt, systemInstruction = '') {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const body = {
    contents: [{ parts: [{ text: prompt }] }],
    generationConfig: {
      temperature: 0.7,
      topP: 0.95,
      maxOutputTokens: 8192,
    },
  };

  if (systemInstruction) {
    body.systemInstruction = { parts: [{ text: systemInstruction }] };
  }

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    const errorMsg = errorData.error?.message || `HTTP ${response.status}: ${response.statusText}`;
    throw new Error(errorMsg);
  }

  const data = await response.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  
  if (!text) {
    throw new Error('No response generated by the model.');
  }

  return text;
}
